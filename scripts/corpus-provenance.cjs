const fs = require('node:fs');
const path = require('node:path');
const { URL } = require('node:url');

const corpusPath = path.resolve(__dirname, '../src/SoundScript.Wordbank/Data/corpus/v2026.07/en/lemmas.json');
const commonsPrefix = 'https://commons.wikimedia.org/wiki/File:';

// A narrative note must never become a Commons file title.
function commonsFile(source) {
  const match = /^Wikimedia Commons — ([^/\\?#<>\r\n]+\.(?:wav|ogg|oga|flac|mp3))$/i.exec(source ?? '');
  return match?.[1] ?? null;
}

function sourceUrl(entry) {
  if (entry.provenanceStatus === 'unresolved') return null;
  if (entry.sourceUrl) return entry.sourceUrl;
  const file = commonsFile(entry.source);
  return file ? commonsPrefix + encodeURIComponent(file) : null;
}

function validateEntry(entry, evidenceRoot = path.dirname(corpusPath)) {
  const errors = [];
  const status = entry.provenanceStatus ?? 'declared';
  if (!['declared', 'unresolved', 'verified'].includes(status)) errors.push('unknown provenance status');
  if (status === 'unresolved') {
    if (!entry.provenanceNote?.trim()) errors.push('unresolved provenance needs a note');
    if (entry.sourceUrl || entry.provenanceEvidence) errors.push('unresolved record must not claim a source URL or verification receipt');
  } else if (!sourceUrl(entry)) errors.push('unrecognized source must be marked unresolved');
  const url = entry.sourceUrl ?? sourceUrl(entry);
  if (url) {
    try {
      const parsed = new URL(url);
      if (!['https:', 'http:'].includes(parsed.protocol) || !parsed.hostname || parsed.username || parsed.password || /\s/.test(url))
        errors.push('invalid source URL');
      if (parsed.hostname === 'commons.wikimedia.org' &&
          (!url.startsWith(commonsPrefix) || !commonsFile('Wikimedia Commons — ' + decodeURIComponent(url.slice(commonsPrefix.length)))))
        errors.push('invalid Commons audio file URL');
    } catch { errors.push('invalid source URL'); }
  }
  if (status === 'verified') {
    const receipt = entry.provenanceEvidence;
    if (!receipt || path.isAbsolute(receipt) || receipt.split(/[/\\]/).includes('..') ||
        !fs.existsSync(path.join(evidenceRoot, receipt))) errors.push('verified provenance requires a repository evidence file');
  }
  return errors;
}

function annotateUnresolved(document) {
  for (const entry of document.entries) {
    if (!commonsFile(entry.source) && !entry.sourceUrl && !entry.provenanceStatus) {
      entry.provenanceStatus = 'unresolved';
      entry.provenanceNote = 'Original recording/generation receipt is missing. The license and attribution fields are historical declarations, not verified provenance.';
    }
  }
}

function renderSources(document) {
  const escape = text => String(text ?? '').replace(/[|\r\n]/g, ' ').replace(/[<>]/g, '');
  const rows = document.entries.map(entry => {
    const url = sourceUrl(entry);
    const source = url ? `[source](${url})` : escape(entry.provenanceNote);
    return `| \`${escape(entry.lemma)}\` | ${escape(entry.license)} | ${entry.provenanceStatus ?? 'declared'} | ${source} |`;
  });
  return `# English pronunciation sources (v2026.07)\n\n` +
    `Generated by \`node scripts/corpus-provenance.cjs --write\` from this directory's \`lemmas.json\`.\n\n` +
    `License values are historical declarations, not legal conclusions. **declared** means a source was recorded;\n` +
    `this validation does not verify that source or its license. **verified** requires a repository evidence receipt\n` +
    `and human review; no entry is promoted to verified by this tool. **unresolved** means source evidence is missing.\n` +
    `The five unresolved pilot clips remain usable assets, but their original source, generation history and license\n` +
    `need external evidence. No Commons URL is constructed from their explanatory text.\n\n` +
    `Historical context: the [pinned wordbank changelog](https://github.com/dharangutti/soundscript-wordbank/blob/10a5b2a8d49fbc38ba99a4f322016e7772b797d5/CHANGELOG.md)\n` +
    `describes the pilot clips as synthesized offline, but supplies no generator/version/input receipt.\n` +
    `That assertion does not establish source provenance or validate the declared CC0 license.\n\n` +
    `| Lemma | Declared license | Provenance status | Source / remaining action |\n|---|---|---|---|\n` + rows.join('\n') + '\n';
}

function main() {
  const write = process.argv.includes('--write');
  const document = JSON.parse(fs.readFileSync(corpusPath, 'utf8'));
  if (write) annotateUnresolved(document);
  const errors = document.entries.flatMap(entry => validateEntry(entry).map(error => `${entry.lemma}: ${error}`));
  if (errors.length) throw new Error(errors.join('\n'));
  const markdown = renderSources(document);
  const sourcesPath = path.join(path.dirname(corpusPath), 'SOURCES.md');
  if (write) {
    document.description = 'English pilot pronunciations with declared license metadata; see SOURCES.md for unresolved provenance.';
    fs.writeFileSync(corpusPath, JSON.stringify(document, null, 2).replaceAll('—', '\\u2014')
      .replace(/"gain": (-?\d+)(,?\n)/g, '"gain": $1.0$2') + '\n');
    fs.writeFileSync(sourcesPath, markdown);
  } else if (fs.readFileSync(sourcesPath, 'utf8').replaceAll('\r\n', '\n') !== markdown) {
    throw new Error('SOURCES.md is stale; run node scripts/corpus-provenance.cjs --write');
  }
  const unresolved = document.entries.filter(entry => entry.provenanceStatus === 'unresolved').map(entry => entry.lemma);
  console.log(`Validated ${document.entries.length} records; unresolved (${unresolved.length}): ${unresolved.join(', ')}`);
}

module.exports = { commonsFile, sourceUrl, validateEntry, annotateUnresolved, renderSources };
if (require.main === module) main();
